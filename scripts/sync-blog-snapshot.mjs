#!/usr/bin/env node
/**
 * Writes src/data/blog-db-snapshot.ts from the blog_posts table.
 *
 * Posts published by the scheduled generator live only in the database, so the
 * build-time sitemap and per-route <head> injection could not see them: 18 of
 * the site's blog URLs were reachable only after the React bundle ran, which is
 * why Search Console had them at "Discovered - currently not indexed".
 *
 * The SEO plugin fetches the live table at build time and falls back to this
 * committed snapshot when the build has no network access, so coverage never
 * silently drops back to the static seed list.
 *
 * Usage: node scripts/sync-blog-snapshot.mjs
 */
import { writeFileSync } from "node:fs";
import { readFileSync } from "node:fs";

const env = Object.fromEntries(
  readFileSync(".env", "utf8")
    .split("\n")
    .filter((l) => l.includes("="))
    .map((l) => [l.slice(0, l.indexOf("=")).trim(), l.slice(l.indexOf("=") + 1).trim().replace(/^"|"$/g, "")]),
);

const url = process.env.VITE_SUPABASE_URL ?? env.VITE_SUPABASE_URL;
const key = process.env.VITE_SUPABASE_PUBLISHABLE_KEY ?? env.VITE_SUPABASE_PUBLISHABLE_KEY;
if (!url || !key) {
  console.error("Missing VITE_SUPABASE_URL / VITE_SUPABASE_PUBLISHABLE_KEY");
  process.exit(1);
}

const res = await fetch(
  `${url}/rest/v1/blog_posts?select=slug,title,description,published_at&order=published_at.desc`,
  { headers: { apikey: key, Authorization: `Bearer ${key}` } },
);
if (!res.ok) {
  console.error(`blog_posts fetch failed [${res.status}]: ${await res.text()}`);
  process.exit(1);
}

const rows = (await res.json()).map((p) => ({
  slug: p.slug,
  title: p.title,
  description: p.description,
  publishedAt: String(p.published_at).slice(0, 10),
}));

const file = `// AUTO-GENERATED by scripts/sync-blog-snapshot.mjs. Do not edit by hand.
//
// Fallback copy of the database blog posts, used by vite-plugin-seo-routes.ts
// when a build cannot reach the database. Keeps every published article in the
// sitemap and in the crawler link index even offline.
export interface BlogDbPost {
  slug: string;
  title: string;
  description: string;
  publishedAt: string;
}

export const blogDbSnapshot: BlogDbPost[] = ${JSON.stringify(rows, null, 2)};
`;

writeFileSync("src/data/blog-db-snapshot.ts", file);
console.log(`blog-db-snapshot.ts written (${rows.length} posts)`);
