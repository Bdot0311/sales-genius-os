#!/usr/bin/env node
/**
 * Bundle the GTM skills into a module the edge functions can import.
 *
 * The skills live in .claude/skills as authoring material. Supabase only
 * deploys what sits under supabase/functions, so an edge function cannot read
 * them at runtime — which is why their frameworks ended up retyped by hand into
 * generate-email's prompts, where they drift from the source the moment either
 * side is edited.
 *
 * This makes the skill the single source: the markdown is compiled into
 * _shared/skills.generated.ts, imported like any other module, and injected
 * into the prompt at request time.
 *
 * Only SKILL.md is bundled, never the references directories. Those run to
 * hundreds of kilobytes (impeccable alone is ~322KB) and would dwarf the email
 * being written. A skill's SKILL.md is the part that states the framework.
 *
 * Run: node scripts/build-skills.mjs        (writes the module)
 *      node scripts/build-skills.mjs --check (fails if it is stale — CI)
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const SKILLS_DIR = ".claude/skills";
const OUT = "supabase/functions/_shared/skills.generated.ts";

// Skills that describe how to write outbound. `impeccable` is a code-quality
// skill and `company-context` is product/brand fact, neither of which belongs in
// a copywriting prompt — generate-email already sources company facts from the
// database, where they are per-user rather than baked into a bundle.
const EMAIL_SKILLS = [
  // Applies to every draft rather than being routed by goal — see STYLE_FLOOR
  // in _shared/email-skills.ts.
  "anti-ai-slop-writing",
  "b2b-cold-email-copywriting",
  "cold-email-4-sequence",
  "cold-email-strategist",
  "cold-email-templates-34",
  "email-writing-frameworks",
  "frontal-messaging-templates",
  "outreach-messaging",
];

/** Strip YAML frontmatter so only the body reaches the prompt. */
function stripFrontmatter(text) {
  if (!text.startsWith("---")) return text;
  const end = text.indexOf("\n---", 3);
  return end === -1 ? text : text.slice(text.indexOf("\n", end + 1) + 1);
}

function build() {
  const available = existsSync(SKILLS_DIR)
    ? readdirSync(SKILLS_DIR, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name)
    : [];

  const missing = EMAIL_SKILLS.filter((n) => !available.includes(n));
  if (missing.length) {
    throw new Error(
      `skills missing from ${SKILLS_DIR}: ${missing.join(", ")}. ` +
        "Install them (see skills-lock.json) before building.",
    );
  }

  const entries = EMAIL_SKILLS.map((name) => {
    const path = join(SKILLS_DIR, name, "SKILL.md");
    const body = stripFrontmatter(readFileSync(path, "utf8")).trim();
    return [name, body];
  });

  const body = entries
    .map(([name, text]) => `  ${JSON.stringify(name)}: ${JSON.stringify(text)},`)
    .join("\n");

  return `// GENERATED by scripts/build-skills.mjs — do not edit.
//
// Source: ${SKILLS_DIR}/<name>/SKILL.md. Edit the skill and re-run the script;
// editing this file directly puts it out of sync with the skill it came from,
// which is the drift this generation step exists to prevent.
//
// References directories are deliberately excluded — see the script header.

export type EmailSkillName =
${entries.map(([n]) => `  | ${JSON.stringify(n)}`).join("\n")};

export const EMAIL_SKILLS: Record<EmailSkillName, string> = {
${body}
};
`;
}

const generated = build();

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== generated) {
    console.error(
      `✗ skills: ${OUT} is out of date with ${SKILLS_DIR}.\n\n` +
        "  Run `node scripts/build-skills.mjs` and commit the result.\n",
    );
    process.exit(1);
  }
  console.log(`✓ skills: ${OUT} matches ${SKILLS_DIR}.`);
} else {
  writeFileSync(OUT, generated);
  const kb = (generated.length / 1024).toFixed(1);
  console.log(`✓ skills: wrote ${OUT} (${EMAIL_SKILLS.length} skills, ${kb}KB).`);
}
